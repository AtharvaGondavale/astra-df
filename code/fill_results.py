"""
ASTRA-DF :: Stage 3 -- turn results.json into LaTeX macros
==========================================================

Generates ``results_auto.tex``, which main.tex \\input's. Every number in the
paper is then a macro like ``\\R{transformer.f1}`` that resolves to a measured
value -- or renders as a red ``??`` if that experiment has not been run yet.

That last property is the point: you can compile the paper at any moment and
instantly see which cells are still unsupported by data.

    python fill_results.py --results results.json --out ../paper/results_auto.tex
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HEADER = r"""% ---------------------------------------------------------------------------
% AUTO-GENERATED by fill_results.py -- do not edit by hand.
% Source: %(src)s
% Generated: %(when)s
%
% \R{key} expands to a measured value, or a red ?? if that experiment has
% not been run. Compile and grep the PDF for ?? to find unsupported cells.
% ---------------------------------------------------------------------------
\providecommand{\R}[1]{%
  \expandafter\ifx\csname RES@#1\endcsname\relax
    \textcolor{red}{\textbf{??}}%
  \else
    \csname RES@#1\endcsname
  \fi}
\providecommand{\setres}[2]{\expandafter\gdef\csname RES@#1\endcsname{#2}}
"""


def fmt(v, nd=3):
    if v is None:
        return None
    try:
        return f"{float(v):.{nd}f}"
    except (TypeError, ValueError):
        return str(v)


def build(results_path: str, out_path: str) -> dict:
    import time

    data = json.load(open(results_path))
    lines: list[str] = []
    missing: list[str] = []

    def put(key, val):
        # Underscores are catcode 8 in LaTeX and would break \csname lookups,
        # so every key is normalised to hyphens. main.tex must match.
        key = key.replace("_", "-")
        if val is None:
            missing.append(key)
            return
        lines.append(f"\\setres{{{key}}}{{{val}}}")

    # ---------------- per-run metrics ----------------
    runs = {k[5:]: v for k, v in data.items() if k.startswith("run::")}
    for name, r in runs.items():
        clip = r.get("test", {}).get("clip", {})
        loc = r.get("test", {}).get("localization", {})
        for m in ("accuracy", "precision", "recall", "f1", "auc"):
            put(f"{name}.{m}", fmt(clip.get(m)))
        for thr in ("0.5", "0.75", "0.95"):
            put(f"{name}.ap{thr}", fmt(loc.get(f"AP@{thr}")))
        put(f"{name}.map", fmt(loc.get("mAP")))
        if r.get("params"):
            put(f"{name}.params", f"{r['params']/1e6:.2f}")
        put(f"{name}.epochs", r.get("epochs"))
        put(f"{name}.minutes", r.get("minutes"))

    # dataset scale (identical across runs -- take the first)
    if runs:
        any_run = next(iter(runs.values()))
        for k in ("n_train", "n_val", "n_test"):
            put(f"data.{k}", any_run.get(k))

    # ---------------- model statistics ----------------
    st = data.get("stats", {})
    for bk in ("transformer", "bilstm"):
        s = st.get(bk, {})
        if s.get("total_params"):
            put(f"{bk}.paramsM", f"{s['total_params']/1e6:.2f}")
        put(f"{bk}.cpums", fmt(s.get("cpu_latency_ms"), 1))
        put(f"{bk}.gpums", fmt(s.get("gpu_latency_ms"), 2))
        put(f"{bk}.fps", fmt(s.get("fps_equivalent"), 1))
        if s.get("flops"):
            put(f"{bk}.gflops", f"{s['flops']/1e9:.2f}")
        for cname, cval in (s.get("components") or {}).items():
            put(f"{bk}.comp.{cname}", f"{cval/1e6:.2f}")

    if st.get("audio_encoder_channels_measured"):
        put("audio.channels",
            ", ".join(str(c) for c in st["audio_encoder_channels_measured"]))
    shapes = st.get("tensor_shapes", {})
    if shapes.get("audio"):
        put("data.Ta", shapes["audio"][0])
    if shapes.get("video"):
        put("data.T", shapes["video"][0])

    # ---------------- cross-dataset (zero-shot) ----------------
    for key, r in data.items():
        if not key.startswith("crossdata::"):
            continue
        nm = key[11:]
        clip = r.get("clip", {})
        for m in ("accuracy", "precision", "recall", "f1", "auc"):
            put(f"{nm}.{m}", fmt(clip.get(m)))
        loc = r.get("localization", {})
        put(f"{nm}.ap0.5", fmt(loc.get("AP@0.5")))
        put(f"{nm}.nclips", r.get("n_clips"))
        put(f"{nm}.nfake", r.get("n_fake"))
        put(f"{nm}.nreal", r.get("n_real"))
        # per-manipulation detection rate: "audio only" -> {nm}.pm.audio-only
        for bucket, val in (r.get("per_manipulation") or {}).items():
            put(f"{nm}.pm.{bucket.replace(' ', '-')}", fmt(val))

    # ---------------- robustness ----------------
    rb = data.get("robustness_audio_noise", {})
    for k, v in rb.items():
        put(f"robust.{k.replace('_', '')}", fmt(v))

    # ---------------- grad-cam ----------------
    gc = data.get("gradcam", {})
    if gc.get("mean_mass_fake") is not None:
        put("gradcam.fake", f"{100*gc['mean_mass_fake']:.0f}")
    if gc.get("mean_mass_real") is not None:
        put("gradcam.real", f"{100*gc['mean_mass_real']:.0f}")
    put("gradcam.nfake", gc.get("n_fake"))
    put("gradcam.nreal", gc.get("n_real"))

    # ---------------- multi-seed aggregate (reviewer item 1) ----------------
    # Emitted only if the multiseed stage has actually been run. Until then the
    # \R{ms...} keys stay unset and render as red ?? -- which is the point:
    # the paper must not quote a mean+-std that does not exist yet.
    seed_stats = Path(results_path).parent / "seed_stats.json"
    if seed_stats.exists():
        ss = json.loads(seed_stats.read_text())
        for var, rec in (ss.get("variants") or {}).items():
            put(f"ms.{var}.seeds", ", ".join(str(s) for s in rec["seeds"]))
            put(f"ms.{var}.nseeds", len(rec["seeds"]))
            for m, st in (rec.get("stats") or {}).items():
                mk = m.replace(".", "")            # ap0.5 -> ap05
                put(f"ms.{var}.{mk}.mean", fmt(st["mean"]))
                put(f"ms.{var}.{mk}.std", fmt(st.get("std")))
                if st["mean"] is not None and st.get("std") is not None:
                    put(f"ms.{var}.{mk}", f"{st['mean']:.3f} $\\pm$ {st['std']:.3f}")
                for sd, val in zip(rec["seeds"], st.get("values", [])):
                    put(f"ms.{var}.{mk}.s{sd}", fmt(val))
        for cname, c in (ss.get("comparisons") or {}).items():
            for m in ("f1", "auc", "ap0.5"):
                if m not in c:
                    continue
                mk = m.replace(".", "")
                pt = c[m]["paired"]
                put(f"ms.{cname}.{mk}.diff", fmt(pt.get("mean_diff")))
                put(f"ms.{cname}.{mk}.p", fmt(pt.get("p"), 4))
                ci = pt.get("ci95") or [None, None]
                if ci[0] is not None:
                    put(f"ms.{cname}.{mk}.ci",
                        f"[{ci[0]:+.3f}, {ci[1]:+.3f}]")
                put(f"ms.{cname}.{mk}.dz", fmt(c[m].get("cohens_dz"), 2))

    # ---------------- per-bucket analysis with FPR context -----------------
    bucket = Path(results_path).parent / "bucket_analysis.json"
    if bucket.exists():
        ba = json.loads(bucket.read_text())
        for scope, buckets in ba.items():
            tag = scope.replace("::", ".").replace("_", "-")
            for bname, b in buckets.items():
                bk = bname.replace(" ", "-")
                # 4 dp: the zero-shot visual-only rate is ~0.0035, which 3 dp
                # would render as "0.003" and drop a significant figure from a
                # number the paper quotes directly.
                put(f"bk.{tag}.{bk}.rate", fmt(b["rate"], 4))
                put(f"bk.{tag}.{bk}.n", b["n"])
                put(f"bk.{tag}.{bk}.ci",
                    f"[{b['ci95'][0]:.4f}, {b['ci95'][1]:.4f}]")

    # ---------------- native ROI resolution --------------------------------
    roi_file = Path(results_path).parent / "roi_native_size.json"
    if roi_file.exists():
        rj = json.loads(roi_file.read_text())
        for corpus, r in rj.items():
            if not isinstance(r, dict) or "crop_side_median_px" not in r:
                continue
            tag = (corpus.replace("/", "-").replace("_", "-")
                         .replace(" ", "").lower())
            put(f"roi.{tag}.side", f"{r['crop_side_median_px']:.0f}")
            put(f"roi.{tag}.w", f"{r['lip_box_w_median_px']:.0f}")
            put(f"roi.{tag}.h", f"{r['lip_box_h_median_px']:.0f}")
            put(f"roi.{tag}.up96", f"{r['frac_upsampled_at_96']*100:.0f}")
            put(f"roi.{tag}.up128", f"{r['frac_upsampled_at_128']*100:.0f}")
            put(f"roi.{tag}.src", ", ".join(r.get("source_resolutions", [])[:2]))

    body = "\n".join(lines) + "\n"
    # NB: HEADER is full of LaTeX % comments, so %-formatting is unusable here.
    head = (HEADER.replace("%(src)s", str(results_path))
                  .replace("%(when)s", time.strftime("%Y-%m-%d %H:%M")))
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(head + "\n" + body)

    print(f"wrote {len(lines)} macros -> {out_path}")
    print(f"runs found: {', '.join(sorted(runs)) or '(none)'}")
    if missing:
        print(f"\n{len(missing)} keys unresolved (will render as red ?? in the PDF):")
        for k in missing[:40]:
            print("   ", k)
        if len(missing) > 40:
            print(f"    ... and {len(missing)-40} more")
    return {"written": len(lines), "missing": missing}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results.json")
    ap.add_argument("--out", default="../paper/results_auto.tex")
    args = ap.parse_args()
    build(args.results, args.out)


if __name__ == "__main__":
    main()
